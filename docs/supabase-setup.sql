-- Supabase 初始化 SQL
-- 在 Supabase 控制台 → SQL Editor → New query，粘贴全部内容后 Run。

-- 1. 建表
create table if not exists public.polls (
  id bigint generated by default as identity primary key,
  title text not null,
  description text default '',
  created_by text,
  created_at timestamptz not null default now()
);

create table if not exists public.poll_options (
  id bigint generated by default as identity primary key,
  poll_id bigint not null references public.polls(id) on delete cascade,
  text text not null
);

create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  poll_id bigint not null references public.polls(id) on delete cascade,
  option_id bigint not null references public.poll_options(id) on delete cascade,
  username text not null,
  created_at timestamptz not null default now(),
  unique (poll_id, username)  -- 每个用户对同一个投票只能投一次
);

-- 2. 开放访问权限（演示用，anon key 即可读写）
-- 显式授权，确保无论项目里“自动开放新表”开关是否勾选，Data API 都能访问这些表
grant usage on schema public to anon, authenticated;
grant select, insert, delete on public.polls, public.poll_options, public.votes to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

alter table public.polls enable row level security;
alter table public.poll_options enable row level security;
alter table public.votes enable row level security;

drop policy if exists "polls_read" on public.polls;
create policy "polls_read" on public.polls for select to anon, authenticated using (true);
drop policy if exists "polls_insert" on public.polls;
create policy "polls_insert" on public.polls for insert to anon, authenticated with check (true);
drop policy if exists "polls_delete" on public.polls;
create policy "polls_delete" on public.polls for delete to anon, authenticated using (true);

drop policy if exists "options_read" on public.poll_options;
create policy "options_read" on public.poll_options for select to anon, authenticated using (true);
drop policy if exists "options_insert" on public.poll_options;
create policy "options_insert" on public.poll_options for insert to anon, authenticated with check (true);

drop policy if exists "votes_read" on public.votes;
create policy "votes_read" on public.votes for select to anon, authenticated using (true);
drop policy if exists "votes_insert" on public.votes;
create policy "votes_insert" on public.votes for insert to anon, authenticated with check (true);

